export async function POST(req) {
  try {
    const { question, mode, history } = await req.json();
    if (!question) {
      return Response.json({ error: "لم يتم إرسال سؤال" }, { status: 400 });
    }

    const modeInstruction = MODE_INSTRUCTIONS[mode] || MODE_INSTRUCTIONS.fatwa;

    const model = genAI.getGenerativeModel({
      model: "gemini-3.5-flash-lite",
      systemInstruction: `${BASE_RULES}\n\n${modeInstruction}`,
    });

    // Gemini يشترط أن تبدأ المحادثة برسالة "user" — نحذف أي رسائل بوت (زي رسالة الترحيب الثابتة) من بداية القائمة
    const rawHistory = (history || []).map((m) => ({
      role: m.role === "user" ? "user" : "model",
      parts: [{ text: m.text }],
    }));
    while (rawHistory.length > 0 && rawHistory[0].role !== "user") {
      rawHistory.shift();
    }

    const chat = model.startChat({ history: rawHistory });

    const result = await chat.sendMessage(question);
    const answer = result.response.text();

    return Response.json({ answer, sources: [] });
  } catch (err) {
    console.error(err);
    return Response.json({ error: "حدث خطأ في المساعد الذكي" }, { status: 500 });
  }
}